package main

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Linux distributions without systemd (Artix, Void, Devuan, Gentoo, ...)
// use init systems kardianos/service doesn't cover. runit and dinit are
// handled here; OpenRC and SysV go through kardianos; s6-rc needs its
// database recompiled, so `install` prints the steps.

// initSystem manages the service on one init system.
type initSystem interface {
	name() string
	install(exe string, args []string) error
	uninstall() error
	control(cmd string) error
}

// pid1 returns the name of the init process.
func pid1() string {
	raw, err := os.ReadFile("/proc/1/comm")
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(raw))
}

// nativeInit returns a handler when PID 1 is an init system that
// kardianos/service can't manage.
func nativeInit() initSystem {
	switch c := pid1(); {
	case c == "runit" || c == "runit-init":
		// Artix keeps services in /etc/runit/sv, Void in /etc/sv.
		if dirExists("/etc/runit/sv") {
			return runitInit{sv: "/etc/runit/sv", enabled: "/run/runit/service", persist: "/etc/runit/runsvdir/default"}
		}
		return runitInit{sv: "/etc/sv", enabled: "/var/service"}
	case c == "dinit":
		return dinitInit{}
	case strings.HasPrefix(c, "s6"):
		return s6Init{}
	}
	return nil
}

func dirExists(p string) bool {
	fi, err := os.Stat(p)
	return err == nil && fi.IsDir()
}

const serviceName = "berylliumd"

// shellQuote quotes for /bin/sh.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func execLine(exe string, args []string) string {
	parts := []string{shellQuote(exe)}
	for _, a := range args {
		parts = append(parts, shellQuote(a))
	}
	return strings.Join(parts, " ")
}

func runCmd(name string, args ...string) error {
	out, err := exec.Command(name, args...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(out)))
	}
	if s := strings.TrimSpace(string(out)); s != "" {
		fmt.Println(s)
	}
	return nil
}

type runitInit struct{ sv, enabled, persist string }

func (r runitInit) name() string { return "runit" }

func (r runitInit) dir() string { return filepath.Join(r.sv, serviceName) }

func (r runitInit) install(exe string, args []string) error {
	if err := os.MkdirAll(r.dir(), 0o755); err != nil {
		return err
	}
	run := "#!/bin/sh\n# Generated by `berylliumd install`.\nexec 2>&1\nexec " + execLine(exe, args) + "\n"
	if err := os.WriteFile(filepath.Join(r.dir(), "run"), []byte(run), 0o755); err != nil {
		return err
	}
	// Linking enables and starts it (runsvdir picks it up within 5s).
	for _, d := range []string{r.persist, r.enabled} {
		if d == "" || !dirExists(d) {
			continue
		}
		link := filepath.Join(d, serviceName)
		if _, err := os.Lstat(link); err == nil {
			continue
		}
		if err := os.Symlink(r.dir(), link); err != nil {
			return err
		}
	}
	return nil
}

func (r runitInit) uninstall() error {
	_ = runCmd("sv", "down", serviceName)
	for _, d := range []string{r.enabled, r.persist} {
		if d != "" {
			_ = os.Remove(filepath.Join(d, serviceName))
		}
	}
	return os.RemoveAll(r.dir())
}

func (r runitInit) control(cmd string) error {
	switch cmd {
	case "start":
		return runCmd("sv", "up", serviceName)
	case "stop":
		return runCmd("sv", "down", serviceName)
	case "restart":
		return runCmd("sv", "restart", serviceName)
	case "status":
		return runCmd("sv", "status", serviceName)
	}
	return fmt.Errorf("unknown command %q", cmd)
}

type dinitInit struct{}

func (dinitInit) name() string { return "dinit" }

const dinitFile = "/etc/dinit.d/" + serviceName

func (dinitInit) install(exe string, args []string) error {
	// The daemon waits for the network itself, so no dependencies.
	svc := "# Generated by `berylliumd install`.\ntype = process\ncommand = " + execLine(exe, args) +
		"\nrestart = true\nsmooth-recovery = true\nstop-timeout = 20\n"
	if err := os.WriteFile(dinitFile, []byte(svc), 0o644); err != nil {
		return err
	}
	return runCmd("dinitctl", "enable", serviceName)
}

func (dinitInit) uninstall() error {
	_ = runCmd("dinitctl", "disable", serviceName)
	_ = runCmd("dinitctl", "stop", serviceName)
	return os.Remove(dinitFile)
}

func (dinitInit) control(cmd string) error {
	switch cmd {
	case "start", "stop", "restart", "status":
		return runCmd("dinitctl", cmd, serviceName)
	}
	return fmt.Errorf("unknown command %q", cmd)
}

type s6Init struct{}

func (s6Init) name() string { return "s6" }

func (s6Init) install(exe string, args []string) error {
	dir := "/etc/s6/sv/" + serviceName
	if err := os.MkdirAll(filepath.Join(dir, "dependencies.d"), 0o755); err != nil {
		return err
	}
	files := map[string]string{
		"type":                "longrun\n",
		"run":                 "#!/bin/sh\nexec 2>&1\nexec " + execLine(exe, args) + "\n",
		"dependencies.d/base": "",
	}
	for name, body := range files {
		mode := os.FileMode(0o644)
		if name == "run" {
			mode = 0o755
		}
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), mode); err != nil {
			return err
		}
	}
	fmt.Printf("s6 service written to %s. Enable it with:\n"+
		"  touch /etc/s6/adminsv/default/contents.d/%s\n  s6-db-reload\n  s6-rc -u change %s\n", dir, serviceName, serviceName)
	return nil
}

func (s6Init) uninstall() error {
	_ = runCmd("s6-rc", "-d", "change", serviceName)
	_ = os.Remove("/etc/s6/adminsv/default/contents.d/" + serviceName)
	return os.RemoveAll("/etc/s6/sv/" + serviceName)
}

func (s6Init) control(cmd string) error {
	switch cmd {
	case "start":
		return runCmd("s6-rc", "-u", "change", serviceName)
	case "stop":
		return runCmd("s6-rc", "-d", "change", serviceName)
	case "restart":
		return errors.Join(runCmd("s6-rc", "-d", "change", serviceName), runCmd("s6-rc", "-u", "change", serviceName))
	case "status":
		return runCmd("s6-svstat", "/run/service/"+serviceName)
	}
	return fmt.Errorf("unknown command %q", cmd)
}
